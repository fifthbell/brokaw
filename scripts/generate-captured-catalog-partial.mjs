import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const partialPath = join(root, 'src/templates/partials/shell/captured-catalog.hbs');
const entryId = 'virtual:brokaw-captured-catalog-entry';
const installer = join(root, 'src/captured-catalog-browser.ts');
const contract = join(root, 'src/captured-catalog.ts');
const outletId = 'virtual:brokaw-captured-catalog-outlet';

/**
 * The contract reads only `outletConfig.supportedLanguages`. The page bundle
 * carries exactly that field, never the rest of the outlet configuration.
 */
async function supportedLanguagesModule() {
  const source = await readFile(contract, 'utf8');
  const fields = new Set([...source.matchAll(/outletConfig\.(\w+)/g)].map((match) => match[1]));
  if (fields.size !== 1 || !fields.has('supportedLanguages')) {
    throw new Error('src/captured-catalog.ts reads outlet fields the page bundle does not carry');
  }
  const { outletConfig } = await import(pathToFileURL(join(root, 'src/outlet-config.ts')).href);
  return `export const outletConfig = { supportedLanguages: ${JSON.stringify(outletConfig.supportedLanguages)} };\n`;
}

/**
 * Bundles src/captured-catalog-browser.ts into the declared partial that pages
 * with a captured selection render. The partial is committed because Cronkite
 * compiles the packaged templates directly; a unit test keeps it current.
 */
export async function generateCapturedCatalogPartial() {
  const outletModule = await supportedLanguagesModule();
  const output = await build({
    configFile: false,
    logLevel: 'silent',
    plugins: [{
      name: 'brokaw-captured-catalog-entry',
      enforce: 'pre',
      resolveId: (id, importer) => {
        if (id === entryId) return `\0${entryId}`;
        if (id === './outlet-config.js' && importer?.replace(/\\/g, '/').endsWith('/src/captured-catalog.ts')) return `\0${outletId}`;
        return null;
      },
      load: (id) => {
        if (id === `\0${entryId}`) {
          return `import { installCapturedCatalog } from ${JSON.stringify(installer)};\ninstallCapturedCatalog(window);\n`;
        }
        return id === `\0${outletId}` ? outletModule : null;
      },
    }],
    build: {
      write: false,
      minify: true,
      target: 'es2022',
      rollupOptions: { input: entryId, output: { format: 'iife' } },
    },
  });
  const chunks = (Array.isArray(output) ? output : [output]).flatMap((result) => result.output);
  const [chunk] = chunks.filter((item) => item.type === 'chunk');
  const code = chunk.code.trim();
  // Handlebars would interpret these sequences inside the inline script.
  if (code.includes('{{') || code.includes('</script')) {
    throw new Error('Captured catalog bundle contains a sequence the partial cannot embed');
  }
  return "{{!-- Generated by scripts/generate-captured-catalog-partial.mjs from src/captured-catalog-browser.ts. Do not edit. --}}"
    + "<script type='application/json' id='brokaw-captured-selection'>{{{jsonString capturedSelection}}}</script>"
    + `<script>${code}</script>`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const partial = await generateCapturedCatalogPartial();
  const check = process.argv.includes('--check');
  const current = await readFile(partialPath, 'utf8').catch(() => '');
  if (check) {
    if (current !== partial) throw new Error('src/templates/partials/shell/captured-catalog.hbs is stale; run npm run generate:captured-catalog');
  } else {
    await writeFile(partialPath, partial);
    console.log('Generated src/templates/partials/shell/captured-catalog.hbs');
  }
}
